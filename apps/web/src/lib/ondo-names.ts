/** Underlying ticker of an Ondo symbol: `NVDAon` becomes `NVDA`. */
export function underlyingTicker(symbol: string): string {
  return symbol.endsWith("on") ? symbol.slice(0, -2) : symbol;
}

/** The issuer's name for an Ondo symbol, or its ticker when the name is not listed. */
export function ondoName(symbol: string): string {
  const t = underlyingTicker(symbol);
  return ONDO_NAMES[t] ?? t;
}
