#!/usr/bin/env node
// Generates src/abis/*.ts from Foundry artifacts in contracts/out.
// Usage: node scripts/gen-abis.mjs [--out-dir <forge out dir>] [--only A,B] [--strict]
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");
const args = process.argv.slice(2);
const flag = (name) => args.indexOf(name);
const value = (name) => (flag(name) >= 0 ? args[flag(name) + 1] : undefined);

const forgeOut = resolve(value("--out-dir") ?? join(pkgRoot, "../../contracts/out"));
const destDir = join(pkgRoot, "src/abis");
const strict = flag("--strict") >= 0;
const only = value("--only")?.split(",").map((s) => s.trim()).filter(Boolean);

// Contracts whose ABI the SDK exposes. Interfaces and implementations both qualify;
// when both exist the implementation ABI (superset) wins under the plain name.
const DEFAULT_CONTRACTS = [
  "VeradaToken",
  "VeradaFactory",
  "VeradaHook",
  "VeradaLpLocker",
  "FeeVault",
  "CauseRegistry",
  "CauseCatalog",
  "CuratorRegistry",
  "AgentVault",
  "EpochGovernor",
  "DonationDistributor",
  "QuoteRegistry",
  "FeeConsolidator",
  "TokenProfileRegistry",
  "VeradaResolver",
  "TakeoverGovernor",
  "ZamaVotingScheme",
  "IVotingScheme",
  "IPrivateDonationAdapter",
];
const wanted = only ?? DEFAULT_CONTRACTS;

function fail(msg) {
  console.error(`gen-abis: ${msg}`);
  process.exit(1);
}

function isDir(p) {
  try {
    return statSync(p).isDirectory();
  } catch {
    return false;
  }
}

if (!isDir(forgeOut)) {
  fail(`forge output dir not found: ${forgeOut} (run \`forge build\` in contracts/ first)`);
}

// Index every artifact: contract name -> artifact json path (skips build-info and test/script dirs).
const index = new Map();
for (const dirent of readdirSync(forgeOut, { withFileTypes: true })) {
  if (!dirent.isDirectory() || dirent.name === "build-info") continue;
  if (/\.(t|s)\.sol$/.test(dirent.name)) continue;
  const dir = join(forgeOut, dirent.name);
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".json")) continue;
    if (f.split(".").length > 2) continue; // skip compiler-versioned duplicates (Name.0.8.26.json)
    const name = f.slice(0, -".json".length);
    if (!index.has(name)) index.set(name, join(dir, f));
  }
}

const written = [];
const missing = [];
rmSync(destDir, { recursive: true, force: true });
mkdirSync(destDir, { recursive: true });

for (const name of wanted) {
  // Fall back to the interface ABI (IName) when the implementation has not been built.
  const path = index.get(name) ?? index.get(`I${name}`);
  if (!path) {
    missing.push(name);
    continue;
  }
  let artifact;
  try {
    artifact = JSON.parse(readFileSync(path, "utf8"));
  } catch (e) {
    fail(`could not parse ${path}: ${e.message}`);
  }
  if (!Array.isArray(artifact.abi)) fail(`artifact ${path} has no abi array`);
  const ident = `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`;
  const body = JSON.stringify(artifact.abi, null, 2);
  writeFileSync(
    join(destDir, `${name}.ts`),
    `// Generated by scripts/gen-abis.mjs from forge artifacts. Do not edit.\nexport const ${ident} = ${body} as const;\n`,
  );
  written.push({ name, ident });
}

const indexSrc =
  "// Generated by scripts/gen-abis.mjs. Do not edit.\n" +
  written.map(({ name }) => `export * from "./${name}.js";`).join("\n") +
  (written.length ? "\n" : "export {};\n");
writeFileSync(join(destDir, "index.ts"), indexSrc);

console.log(`gen-abis: wrote ${written.length} ABI module(s) to ${destDir}`);
if (missing.length) {
  console.warn(`gen-abis: no artifact found for: ${missing.join(", ")}`);
  if (strict) process.exit(1);
}
